/**
 * Get translation
 */
function t($key, $default = '') {
    global $lang, $translations;
    return $translations[$lang][$key] ?? $translations['ar'][$key] ?? $default ?? $key;
}

/**
 * Get current language
 */
function getLang() {
    global $lang;
    return $lang;
}

/**
 * Get language direction
 */
function getDir() {
    $lang = getLang();
    return ($lang === 'ar' || $lang === 'ku') ? 'rtl' : 'ltr';
}

/**
 * Get language attribute
 */
function getLangAttr() {
    return getLang();
}

/**
 * Echo translation (shorthand)
 */
function _t($key, $default = '') {
    echo t($key, $default);
}

/**
 * Get translation with placeholder replacement
 */
function t_replace($key, $replacements = [], $default = '') {
    $text = t($key, $default);
    foreach ($replacements as $placeholder => $value) {
        $text = str_replace('{' . $placeholder . '}', $value, $text);
    }
    return $text;
}

